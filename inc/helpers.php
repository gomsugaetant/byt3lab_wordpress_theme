/**
 * Lecture d'un réglage du site (option `byt3lab_settings`) avec repli sur les valeurs par défaut.
 * Clé en notation pointée : byt3lab_opt('home.hero.title').
 */
function byt3lab_opt($key, $fallback = '') {
    static $merged = null;
    if ($merged === null) {
        $saved  = get_option('byt3lab_settings', []);
        $saved  = is_array($saved) ? $saved : [];
        $merged = [];
        foreach (byt3lab_settings_schema() as $group) {
            foreach ($group['fields'] as $fkey => $field) {
                $val = $saved[$fkey] ?? '';
                $merged[$fkey] = ($val === '' || $val === null) ? ($field['default'] ?? '') : $val;
            }
        }
    }
    $val = $merged[$key] ?? '';
    return ($val === '') ? $fallback : $val;
}

/** Échappement + rendu d'un réglage texte. */
function byt3lab_e($key) {
    echo esc_html(byt3lab_opt($key));
}

/** Transforme un texte multi-lignes en tableau (une entrée par ligne, lignes vides ignorées). */
function byt3lab_lines($text) {
    if (is_array($text)) {
        return $text;
    }
    return array_values(array_filter(array_map('trim', preg_split('/\r\n|\r|\n/', (string) $text))));
}

/** Méta multi-lignes d'un contenu -> tableau. */
function byt3lab_meta_lines($post_id, $key) {
    return byt3lab_lines(get_post_meta($post_id, $key, true));
}

/** Image d'un contenu : vignette WP (responsive + lazy) ou rien. Aucune image de stock n'est injectée. */
function byt3lab_post_image($post_id, $size = 'large', $attrs = []) {
    if (has_post_thumbnail($post_id)) {
        return get_the_post_thumbnail($post_id, $size, array_merge(['loading' => 'lazy', 'decoding' => 'async'], $attrs));
    }
    return '';
}

